package com.cardamom.ledger.domain.enums;

/**
 * Cardamom varieties cultivated in South Indian plantation belts:
 * - MALABAR: Prostrate panicles, roundish bold pods, highly aromatic, suited for 600-1000m altitudes.
 * - VAZHUKKA: Semi-erect panicles, high-yielding natural cross between Malabar and Mysore, oval pods.
 * - MYSORE: Erect panicles, oblong ribbed pods, cold and altitude resistant (>1000m).
 */
public enum CardamomVariety {
    MALABAR,
    VAZHUKKA,
    MYSORE
}
