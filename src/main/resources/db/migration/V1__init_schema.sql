-- 1. Plantation Blocks (Estate Parcels)
CREATE TABLE plantation_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    variety VARCHAR(30) NOT NULL,
    total_area_acres NUMERIC(8, 2) NOT NULL,
    planting_year INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_blocks_variety ON plantation_blocks (variety);

-- 2. Plantation Operational & Capital Expenses
CREATE TABLE plantation_expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_id BIGINT,
    category VARCHAR(30) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    date DATE NOT NULL,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_expenses_block FOREIGN KEY (block_id) REFERENCES plantation_blocks (id) ON DELETE SET NULL
);

CREATE INDEX idx_expenses_block_id ON plantation_expenses (block_id);
CREATE INDEX idx_expenses_date ON plantation_expenses (date);
CREATE INDEX idx_expenses_category ON plantation_expenses (category);

-- 3. Harvest Batches (Green Yields, Curing & Grading)
CREATE TABLE harvest_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_id BIGINT NOT NULL,
    harvest_date DATE NOT NULL,
    green_weight_kg NUMERIC(10, 2) NOT NULL,
    dry_weight_kg NUMERIC(10, 2),
    bhatti_cost NUMERIC(10, 2),
    grade_breakdown_json TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'RAW',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_batches_block FOREIGN KEY (block_id) REFERENCES plantation_blocks (id) ON DELETE RESTRICT
);

CREATE INDEX idx_batches_block_id ON harvest_batches (block_id);
CREATE INDEX idx_batches_harvest_date ON harvest_batches (harvest_date);
CREATE INDEX idx_batches_status ON harvest_batches (status);

-- 4. Sale Transactions (Auction Realization & Commission)
CREATE TABLE sale_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    buyer_or_auction_house VARCHAR(150) NOT NULL,
    total_quantity_sold_kg NUMERIC(10, 2) NOT NULL,
    price_per_kg NUMERIC(10, 2) NOT NULL,
    commission_deduction NUMERIC(10, 2) NOT NULL,
    net_realization_amount NUMERIC(12, 2) NOT NULL,
    sale_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_sales_batch FOREIGN KEY (batch_id) REFERENCES harvest_batches (id) ON DELETE RESTRICT
);

CREATE INDEX idx_sales_batch_id ON sale_transactions (batch_id);
CREATE INDEX idx_sales_sale_date ON sale_transactions (sale_date);
